namespace asio = boost::asio;


enum class NodeRole : uint8_t{
    CLIENT       = 1 << 0,
    RELAY        = 1 << 1,
    EXIT         = 1 << 2,
    CLIENT_RELAY = (1 << 0) | (1 << 1)
};


/**
 * XXX: Node with CLIENT && RELAY functionalities.
 *
 * Device producer -> tun/utun (handled by unique_ptr client_)
 * Device traffic -> through a upd socket to entry relays (handled by client_)
 * Relay traffic -> through a udp socket (fixed) (handled by relay_)
 * Commns with control_server -> through tcp sockets (handled by client_ and relay_)
 *
 *
 * Questions:
 * Q: does the tun/utun need to be configed to allow
 *          a. traffic to & from control_server
 *          b. traffic handled by the relay_
 * if so, how do we set up commns between the relay_ and the client_?
 *
 * A: NO, the relay_ can set up sockets binded directly to the en0 (wifi) device. traffic
 * to and from that socket is directed directly through that device, doesn't interact with the
 * utun/tun.
 *          unsigned int ifindex = if_nametoindex("en0");
 *          setsockopt(sock_fd, IPPROTO_IP, IP_BOUND_IF, &ifindex, sizeof(ifindex));
 * Things to remember:
 *      1. The utun socket is not an endpoint on the network; it is a file descriptor managed by the OS kernel.
 *      2. Traffic generated by local applications flows into utun automatically because of system routes.
 *      3. client_ must actively read from utun to capture that traffic, wrap it in your protocol, and send it out over en0.
 *
 */


/*
* Node functionalities

setup connection to control_server
get info about ice
connect to ice
analyze nat
assign role (client/client+relay)

*/

class Node : public std::enable_shared_from_this<Node>{
public:
    Node(asio::io_context& ioc, NodeRole role);


    [[nodiscard]] asio::awaitable<bool> start();


    void stop();


    class CommError{
    public:
        explicit CommError(const bool errored, std::string msg):
            erred(errored),
            message(std::move(msg)){}


        explicit CommError(const bool errored){
            if(errored){
                erred = true;
                message = "creator of this error kept the error message secret";
            }
            else
                erred = false;
        }


        explicit CommError(std::string msg):
            erred(true),
            message(std::move(msg)){}


        [[nodiscard]] const char* what() const noexcept{
            return message.c_str();
        }


        explicit operator bool() const noexcept{
            return erred;
        }

    private:
        bool erred;
        std::string message;
    };


    static asio::awaitable<CommError> populate_relays(std::shared_ptr<RelaysInfoGlb> known_relays,
                                                      RelayInfo start_relay,
                                                      std::shared_ptr<asio::ip::udp::socket> udp_sockv4);


    static asio::awaitable<CommError> establish_connection(RelayInfo relay,
                                                           std::shared_ptr<asio::ip::udp::socket> udp_sockv4,
                                                           std::shared_ptr<RelaysInfoGlb> known_relays);


    static void resume_control_operation(txn_id_t txn_id,
                                         std::vector<uint8_t> payload,
                                         std::shared_ptr<RelaysInfoGlb> relays_info_glb);


    using ControlResult = std::variant<std::vector<uint8_t>, CommError>;


    static asio::awaitable<ControlResult> control_send_and_wait_udp(std::shared_ptr<asio::ip::udp::socket> udp_sockv4,
                                                                    std::vector<uint8_t> packet,
                                                                    asio::ip::udp::endpoint endpoint,
                                                                    txn_id_t txn_id,
                                                                    std::shared_ptr<RelaysInfoGlb> relays_info_glb);


    /*
        we need to listen for incoming packets and route it to either client or relay

        proposed idea:
            if first bit of packet is 0:
                circuit_id -> node should use relay to forward it to client
            else:
                session_id
                if second bit of packet is 0:
                    node should deliver packet to client
                else:
                    node should use relay to forward it to exit
    */

private:
    NodeRole role_;

    std::atomic<bool> running_;

    std::shared_ptr<RelaysInfoGlb> relays_info_glb_ = nullptr;
    static constexpr size_t DESIRED_RELAY_COUNT = 10;


    struct udp_comms_config{
        static constexpr size_t max_attempts = 5;
        static constexpr auto start_timeout = std::chrono::milliseconds(100);
    };


    RelayInfo bootstrap_node_;

    std::shared_ptr<Client> client_ = nullptr;
    std::shared_ptr<Relay> relay_ = nullptr;
    std::shared_ptr<Exit> exit_ = nullptr;

    asio::io_context& ioc_;
    std::shared_ptr<asio::ip::udp::socket> udp_socketv4_;
    std::shared_ptr<asio::ip::udp::socket> udp_socketv6_;

    asio::ip::udp::endpoint listening_endpoint_;
    std::shared_ptr<asio::ip::udp::endpoint> sender_endpoint_;

    ArenaAllocator<IncomingCell> incoming_cell_pool_;

    quill::Logger* logger_{nullptr};


    static bool is_relay_diverse(const asio::ip::udp::endpoint& ep, const std::unordered_set<RelayInfo>& existing_relays);


    static std::vector<uint8_t> make_connection_packet(RelayInfo& relay, txn_id_t txn_id);


    static asio::awaitable<std::vector<RelayInfo>> request_relay_list(RelayInfo& relay,
                                                                      std::shared_ptr<asio::ip::udp::socket> udp_sockv4,
                                                                      std::shared_ptr<RelaysInfoGlb> relays_info_glb);


    static std::vector<uint8_t> make_request_relay_list_packet(RelayInfo& relay, txn_id_t txn_id);


    template<class CompletionToken>
    static auto async_wait_for_response(txn_id_t txn_id, CompletionToken&& token, const std::shared_ptr<RelaysInfoGlb>& relays_info_glb){
        using Signature = void(boost::system::error_code, std::vector<uint8_t>);

        return asio::async_initiate<CompletionToken, Signature>(
            [txn_id, relays_info_glb](auto handler){
                auto unbound_handler = [h = std::move(handler)](boost::system::error_code ec, std::vector<uint8_t> data) mutable{
                    h(ec, std::move(data));
                };

                std::mutex& mtx = relays_info_glb->registry_mutex_;
                std::lock_guard<std::mutex> lock(mtx);
                relays_info_glb->pending_requests_[txn_id] = std::move(unbound_handler);
            },
            token
        );
    }


    void listenv4(ArenaSlot<IncomingCell> packet);


    void listenv6(ArenaSlot<IncomingCell> packet);


    void loop_listen(ArenaSlot<IncomingCell> packet, const boost::system::error_code& ec, bool ipv4);


    void route_packet(ArenaSlot<IncomingCell> packet, asio::ip::udp::endpoint endpoint) const;
};
