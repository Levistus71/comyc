constexpr size_t CELL_MAX_SZ = 2000;


struct IncomingCell{
    size_t bytes_received = 0;
    size_t outgoing_bytes = 0;
    size_t payload_bytes = 0;

    RoutingFlag route_flag = RoutingFlag::INVALID;
    size_t start_offset = 0;

    session_id_t sid = 0;
    circuit_id_t cid = 0;
    std::array<uint8_t, CELL_MAX_SZ> payload;
};

class Node : std::enable_shared_from_this<Node>
{
public:
    Node();
    
    void start();
    void stop();

    /*
        we need to listen for incoming packets and route it to either client or relay
        
        proposed idea:
            if first bit of packet is 0:
                circuit_id -> node should use relay to forward it to client
            else:
                session_id
                if second bit of packet is 0:
                    node should deliver packet to client
                else:
                    node should use relay to forward it to exit
    */

private:
    NodeRole role_;

    std::shared_ptr<Client> client_;
    std::shared_ptr<Relay> relay_;
    std::shared_ptr<Exit> exit_;

    asio::io_context ioc_;
    asio::ip::udp::socket udp_socket_;

    asio::ip::udp::endpoint listening_endpoint_;


    void listen(std::shared_ptr<IncomingCell> packet);
    void loop_listen(std::shared_ptr<IncomingCell> packet, const boost::system::error_code& ec);
    void route_packet(std::shared_ptr<IncomingCell> packet);
};